def write_csv(path: Path, rows: list[dict]) -> None:
    if not rows:
        return
    with path.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)


def main() -> None:
    write_csv(ROOT / "commercial-keyword-page-map.csv", COMMERCIAL)
    write_csv(ROOT / "academy-initial-topic-map.csv", ACADEMY)
    print("Wrote commercial and academy maps")


if __name__ == "__main__":
    main()
